"""Person merges shared by the exports: data/external/person_merges.csv (drop_pid -> keep_pid).

person_merges.csv is regenerated by scripts/resolve_duplicates.py on every build. To merge pairs by
hand (e.g. after reviewing duplicate_review.csv), add drop_pid,keep_pid rows to
person_merges_manual.csv, which the build never overwrites. LINEAGE_NO_MERGES=1 disables merging
(used by the build to find duplicates on unmerged data).
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MERGES = ROOT / "data" / "external" / "person_merges.csv"            # written by resolve_duplicates.py
MANUAL = ROOT / "data" / "external" / "person_merges_manual.csv"     # yours: drop_pid,keep_pid[,note]


def load_merges() -> dict[int, int]:
    import os
    if os.environ.get("LINEAGE_NO_MERGES"):
        return {}
    import pandas as pd
    raw = {}
    for f in (MERGES, MANUAL):  # manual rows win
        if f.exists() and f.stat().st_size > 0:
            df = pd.read_csv(f)
            if len(df):
                raw.update({int(r.drop_pid): int(r.keep_pid) for r in df.itertuples(index=False)})
    out = {}
    for d in raw:  # follow chains a -> b -> c
        k, seen = raw[d], {d}
        while k in raw and k not in seen:
            seen.add(k)
            k = raw[k]
        out[d] = k
    return out
